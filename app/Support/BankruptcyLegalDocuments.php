    private function fmt(?string $value, ?string $fallback = null): string
    {
        $value = trim((string) $value);

        return $value !== '' ? $value : ($fallback ?? self::BLANK);
    }

    private function fmtTime(?string $value, ?string $fallback = null): string
    {
        return $this->fmt($value, $fallback ?? self::BLANK);
    }

    private function fmtDate(mixed $date): string
    {
        return $date?->translatedFormat('d F Y') ?? self::BLANK;
    }

    private function money(float $amount): string
    {
        return number_format($amount, 0);
    }
