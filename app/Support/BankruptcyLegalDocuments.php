    private const string BLANK = '................';

    public function claim(BankruptcyCase $case): string
    {
        $courtCity = $case->court_city ?: $case->cr_city;
        $docDate = $this->fmtDate($case->document_date);
        $poaDate = $this->fmtDate($case->poa_date);

        return <<<TEXT
إلى فضيلة رئيس الدائرة التجارية بالمحكمة التجارية الموقرة بمدينة {$courtCity}
فضيلة رئيس وأعضاء الدائرة الموقرين،،، حفظكم الله ورعاكم

الموضوع: طلب افتتاح إجراء التصفية الإدارية لشركة {$case->debtor_name} (ذات سجل تجاري رقم: {$case->cr_number})
التاريخ: {$docDate}  الساعة: {$this->fmtTime($case->document_time)}

السلام عليكم ورحمة الله وبركاته، أما بعد:

بصفتي وكيلاً شرعياً بموجب الوكالة الشرعية الصادرة برقم ({$this->fmt($case->poa_number)}) وتاريخ ({$poaDate}) من كتابة عدل {$this->fmt($case->poa_city, $case->cr_city)}، عن موكلي شركة {$case->debtor_name}، وهي شركة من نوع "{$case->legal_form}" مسجلة بمدينة {$case->cr_city} بموجب السجل التجاري ذي الرقم ({$case->cr_number}) الصادر بتاريخ (....)، ويمثلها {$this->fmt($case->representative_title, 'المدير')} السيد {$case->representative_name} (هوية رقم: {$this->fmt($case->representative_id)}). ويقع مركزها الرئيسي في {$case->cr_city}.

الوقائع والأسانيد:
1. تقدم موكلنا بهذه الدعوى طالباً افتتاح إجراء "التصفية الإدارية"، حيث عجزت الشركة عن الوفاء بالتزاماتها المالية وديونها التي بلغت ({$this->money($case->total_debts)} ريال سعودي) نظراً لركود الأسواق وتعرض الشركة لتعثرات مالية بالغة منعت المنشأة من الاستمرار في ممارسة نشاطها التجاري حيث أصبح النشاط متوقفاً بالكامل.
2. نود إحاطة فضيلتكم بأن القيمة الإجمالية لأصول الشركة وممتلكاتها لا تتجاوز مبلغ ({$this->money($case->total_assets)} ريال سعودي) بناءً على بيان الأصول المرفق، وحيث أن هذه الأصول ضئيلة للغاية ولا تكفي بأي حال من الأحوال لتغطية مصروفات إجراء التصفية العادية أو أتعاب أمين التصفية.
3. استناداً إلى أحكام المادة (168) من نظام الإفلاس الصادر بالمرسوم الملكي رقم (م/50) وتاريخ 1439/05/28هـ، فإن موكلي تنطبق عليه تماماً شروط افتتاح إجراء التصفية الإدارية لكونه مديناً مفلساً لا تكفي أصوله لتغطية مصروفات إجراء التصفية.

الطلبات:
بناءً على ما تقدم من وقائع وأسانيد قانونية، وتأسيساً على نظام الإفلاس السعودي ولائحته التنفيذية، نطلب من دائرتكم الموقرة ما يلي:
أولاً: قبول هذا الطلب شكلاً لتوفر كافة المتطلبات النظامية والشكلية المطلوبة قانوناً.
ثانياً: قيد الطلب وافتتاح إجراء التصفية الإدارية لموكلي شركة {$case->debtor_name}، وإحالة الملف إلى لجنة الإفلاس لاتخاذ شؤونها النظامية بالتصفية.

والله الموفق والمستعان،،
مقدم الطلب/ المحامي الوكيل: {$case->attorney_name}
TEXT;
    }

    public function shareholdersResolution(BankruptcyCase $case): string
    {
        $docDate = $this->fmtDate($case->document_date);

        return <<<TEXT
محضر قرار الشركاء في الجمعية العامة غير العادية
لشركة {$case->debtor_name} (ذات المسؤولية المحدودة)
المسجلة بالسجل التجاري رقم: ({$case->cr_number}) وتاريخ (....) بمدينة {$case->cr_city}

إنه في تاريخ {$docDate}، في تمام الساعة ({$this->fmtTime($case->document_time, '...')}م)، وبمقر الشركة الرئيسي بمدينة {$case->cr_city}، عقد الشركاء في شركة {$case->debtor_name} جمعيتهم العامة غير العادية، وذلك بحضور الشركاء الملاك لكامل رأس المال.

القرارات:
1. الموافقة بالإجماع على تقديم طلب افتتاح إجراء "التصفية الإدارية" بموجب نظام الإفلاس السعودي أمام المحكمة التجارية المختصة.
2. تفويض الأستاذ المحامي/ {$case->attorney_name} (رخصة محاماة رقم: {$case->attorney_license}) في تمثيل الشركة والتوقيع نيابة عنها ومتابعة الطلب أمام المحكمة التجارية ولجنة الإفلاس.
3. التزام الإدارة بالتعاون التام مع لجنة الإفلاس والأمين المعين.

تواقيع الشركاء الحاضرين:
1. (التوقيع: ................)
2. (التوقيع: ................)
TEXT;
    }

    public function creditorsNotice(BankruptcyCase $case): string
    {
        return <<<TEXT
إشعار موجه إلى الدائنين الكرام
بشأن طلب افتتاح إجراء التصفية الإدارية لشركة {$case->debtor_name}

تود إدارة شركة {$case->debtor_name} إحاطة سعادة الدائنين الكرام بأنها بصدد تقديم طلب رسمي لافتتاح إجراء التصفية الإدارية لدى المحكمة التجارية بـ {$case->cr_city} استناداً لنظام الإفلاس السعودي.

وتأتي هذه الخطوة بعد استنفاد كافة السبل التشغيلية، حيث بلغت الديون الإجمالية ({$this->money($case->total_debts)} ريال) مقابل أصول لا تتجاوز ({$this->money($case->total_assets)} ريال).

يهدف هذا الإجراء إلى حفظ حقوق جميع الأطراف وفق الأولويات النظامية المقررة.

عن إدارة شركة {$case->debtor_name}:
المدير التنفيذي/ {$case->representative_name}
TEXT;
    }

    public function powerOfAttorney(BankruptcyCase $case): string
    {
        $courtCity = $case->court_city ?: $case->cr_city;
        $poaCity = $this->fmt($case->poa_city, $case->cr_city);
        $poaDate = $this->fmtDate($case->poa_date);
        $poaNumber = $this->fmt($case->poa_number);

        return <<<TEXT
وكالة شرعية
رقم الوكالة: {$poaNumber}
صادرة بتاريخ: {$poaDate} من كتابة عدل {$poaCity}

أنا/ {$case->representative_name}، {$this->fmt($case->representative_title, 'مدير')} شركة {$case->debtor_name}
رقم الهوية / الإقامة: {$this->fmt($case->representative_id, str_repeat('.', 28))}
السجل التجاري: ({$case->cr_number}) مسجل بمدينة {$case->cr_city}

أوكّل وأفوّض:
الأستاذ المحامي/ {$case->attorney_name}
رقم رخصة المحاماة: {$case->attorney_license}

في القيام بجميع الأعمال القانونية والإجراءات القضائية المتعلقة بتقديم طلب افتتاح إجراء "التصفية الإدارية" لشركة {$case->debtor_name} أمام المحكمة التجارية بمدينة {$courtCity} ولجنة الإفلاس والجهات الحكومية ذات العلاقة، ويحق له:
- تقديم الطلبات والمذكرات والوثائق
- استلام القرارات والأحكام القضائية
- التوقيع نيابة عن الموكل في كل ما يتعلق بهذا الإجراء
- تفويض الغير من زملائه المحامين في سبيل تنفيذ هذه الوكالة

هذه الوكالة سارية المفعول حتى انتهاء إجراءات التصفية الإدارية بصورتها النهائية.

الموكِّل/ {$case->representative_name}
رقم الهوية/الإقامة: {$this->fmt($case->representative_id, str_repeat('.', 28))}

يُعتمد هذا التوقيع أمام: كتابة عدل {$poaCity}
رقم التوثيق: {$poaNumber}  بتاريخ: {$poaDate}
TEXT;
    }

